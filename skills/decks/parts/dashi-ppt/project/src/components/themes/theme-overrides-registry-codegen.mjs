import { normalizeThemeKeys } from './theme-registry-codegen.mjs';

export const THEME_OVERRIDE_KEYS = Object.freeze(['theme02', 'theme03', 'theme04']);

const THEME_OVERRIDE_KEY_SET = new Set(THEME_OVERRIDE_KEYS);

export function buildThemeRuntimeOverrideRegistrySource(
  themeKeys,
  {
    importPrefix = './',
    generated = true,
    fromModules = false,
    moduleSuffix = '.overrides.mjs',
  } = {},
) {
  const normalized = normalizeThemeKeys(themeKeys);
  if (!normalized.length) throw new Error('buildThemeRuntimeOverrideRegistrySource: no accepted theme keys to include.');
  const keys = normalized.filter(key => THEME_OVERRIDE_KEY_SET.has(key));
  const header = generated
    ? '// @generated by theme runtime override registry codegen — do not edit.\n'
    : '';

  if (fromModules) {
    const imports = keys
      .map(key => `import * as ${key}OverrideModule from ${JSON.stringify(`${importPrefix}${key}${moduleSuffix}`)};`)
      .join('\n');
    const modules = keys.map(key => `  ${key}: ${key}OverrideModule,`).join('\n');
    return `${header}${imports}${imports ? '\n\n' : ''}const THEME_OVERRIDE_MODULES = Object.freeze({
${modules}
});

export const THEME_RUNTIME_OVERRIDES = Object.freeze(Object.fromEntries(
  Object.entries(THEME_OVERRIDE_MODULES)
    .map(([key, overrideModule]) => [key, overrideModule.getThemeRuntimeOverride(key)])
    .filter(([, override]) => override),
));

export function getThemeRuntimeOverride(themeKey) {
  return THEME_RUNTIME_OVERRIDES[themeKey];
}
`;
  }

  const imports = keys
    .map(key => `import { overrides as ${key} } from ${JSON.stringify(`${importPrefix}${key}/overrides.js`)};`)
    .join('\n');
  const overrides = keys.map(key => `  ${key},`).join('\n');
  return `${header}${imports}${imports ? '\n\n' : ''}export const THEME_RUNTIME_OVERRIDES = Object.freeze({
${overrides}
});

export function getThemeRuntimeOverride(themeKey) {
  return THEME_RUNTIME_OVERRIDES[themeKey];
}
`;
}
