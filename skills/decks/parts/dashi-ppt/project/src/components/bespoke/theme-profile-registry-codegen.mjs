import { normalizeThemeKeys } from '../themes/theme-registry-codegen.mjs';

export function buildBespokeThemeProfileRegistrySource(
  themeKeys,
  {
    importPrefix = './',
    generated = true,
    fromModules = false,
    moduleSuffix = '.profile.mjs',
  } = {},
) {
  const keys = normalizeThemeKeys(themeKeys);
  if (!keys.length) throw new Error('buildBespokeThemeProfileRegistrySource: no accepted theme keys to include.');

  const header = generated
    ? '// @generated by bespoke theme profile registry codegen — do not edit.\n'
    : '';

  if (fromModules) {
    const imports = keys
      .map(key => `import * as ${key}Profile from ${JSON.stringify(`${importPrefix}${key}${moduleSuffix}`)};`)
      .join('\n');
    const modules = keys.map(key => `  ${key}: ${key}Profile,`).join('\n');
    const fallbackKey = keys[0];
    return `${header}${imports}

const PROFILE_MODULES = Object.freeze({
${modules}
});

export const BESPOKE_FAMILIES = ${fallbackKey}Profile.BESPOKE_FAMILIES;
export const BESPOKE_THEME_PROFILES = Object.freeze(Object.fromEntries(
  Object.entries(PROFILE_MODULES).map(([key, profileModule]) => [key, profileModule.BESPOKE_THEME_PROFILES[key]]),
));

export function getBespokeThemeProfile(themeKey, background = 'default') {
  const key = Object.hasOwn(PROFILE_MODULES, themeKey) ? themeKey : ${JSON.stringify(fallbackKey)};
  return PROFILE_MODULES[key].getBespokeThemeProfile(key, background);
}
`;
  }

  const corePath = `${importPrefix}theme-profile-core.mjs`;
  const imports = keys
    .map(key => `import ${key} from ${JSON.stringify(`${importPrefix}theme-profile-adapters/${key}.mjs`)};`)
    .join('\n');
  const adapters = keys.map(key => `  ${key},`).join('\n');
  return `${header}import {
  BESPOKE_FAMILIES,
  createBespokeThemeProfileRegistry,
} from ${JSON.stringify(corePath)};
${imports}

export { BESPOKE_FAMILIES };

const registry = createBespokeThemeProfileRegistry({
${adapters}
}, { fallbackKey: ${JSON.stringify(keys[0])} });

export const BESPOKE_THEME_PROFILES = registry.profiles;
export const getBespokeThemeProfile = registry.getBespokeThemeProfile;
`;
}
